"""Compare live cart subtotals with our pricing rules (PR-03 checkout evidence).

Reads data/snapshot/checkout-<retailer>.csv (written by scripts/scrape/checkout.ts)
and writes data/snapshot/checkout-evidence.md. For each sampled deal, our rule
is applied to the *live* unit price and deal wording, so a price change since
the snapshot does not count as a disagreement; the cart subtotal must equal it.

Run from the repository root: python3 scripts/checkout_evidence.py
"""

import csv
from pathlib import Path

import re
from decimal import ROUND_HALF_UP, Decimal

from derive_offer_prices import derive_offer, to_cents

PERCENT = re.compile(r"(?:any|buy) (\d+) (?:save|get) (\d+(?:\.\d+)?)%", re.IGNORECASE)


def percentage_rule_cents(price: str, savings: str, qty: int) -> int | None:
    """What the former percentage rule charged: X% off N packs, rounded half-up per deal."""
    match = PERCENT.search(savings)
    unit = to_cents(price)
    if not match or unit is None:
        return None
    packs, percent = int(match[1]), Decimal(match[2])
    deal = int((Decimal(packs * unit) * (100 - percent) / 100).quantize(Decimal(1), ROUND_HALF_UP))
    deals = qty // packs
    return deals * deal + (qty - deals * packs) * unit

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "data" / "snapshot"
RETAILERS = ["fairprice", "cold-storage", "redmart"]


def expected_cents(price: str, savings: str, qty: int) -> tuple[int | None, str]:
    """Our line total for `qty` packs, and the deal it used, from live price and wording."""
    offer = derive_offer({"Product Price": price, "Original Price": "", "Savings": savings})
    if not offer["eligible"]:
        return None, ""
    unit, deal = offer["unit_price_cents"], offer["multibuy"]
    if deal is None:
        return unit * qty, "no deal applied"
    deals = qty // deal["packsPerDeal"]
    rest = qty - deals * deal["packsPerDeal"]
    return deals * deal["dealPriceCents"] + rest * unit, f"{deal['packsPerDeal']} for {deal['dealPriceCents'] / 100:.2f}"


def main() -> None:
    lines = [
        "# Checkout evidence for multibuys (PR-03)",
        "",
        "Generated by `scripts/checkout_evidence.py` from live carts filled by `scripts/scrape/checkout.ts`.",
        "Each sampled deal was put in a cart at one pack more than the deal needs, so the remaining pack",
        "is tested too. *Expected* applies our curation and pricing rules to the live unit price and deal",
        "wording; *Cart* is the retailer's own subtotal. Nothing was ordered. FairPrice carts were filled",
        "as a guest by the script; RedMart's were filled by hand in a logged-in session (Lazada blocks",
        "scripted logins) and recorded in `checkout-redmart.csv`; Cold Storage's cart needs a login, so",
        "its deals were checked against their live product pages only.",
        "",
        "**Finding.** Every fixed-price deal (\"N for $X\") matched the cart at every retailer. RedMart's",
        "percentage deals did not reliably: the cart charges a fixed deal price and the percentage is a",
        "rounded label for it (\"Any 2 Save 40%\" charged $11.79 for $19.78, 40.4% off). Under PR-03 a deal",
        "type the checkout disagrees with stays excluded, so percentage deals are no longer applied; they",
        "show as not included in the estimate.",
        "",
    ]
    totals = {}
    for retailer in RETAILERS:
        path = SNAPSHOT / f"checkout-{retailer}.csv"
        if not path.exists():
            lines += [f"## {retailer}", "", "Not checked yet.", ""]
            continue
        rows = list(csv.DictReader(open(path, encoding="utf-8")))
        lines += [
            f"## {retailer}",
            "",
            "| Product | Qty | Unit | Deal wording | Our deal | Expected | Cart | Result |",
            "| --- | ---: | ---: | --- | --- | ---: | ---: | --- |",
        ]
        agree = checked = terms = percentage = percentage_agree = 0
        for row in rows:
            name = row["url"].rstrip("/").rsplit("/", 1)[-1].removesuffix(".html")
            if row["note"] == "terms only":
                expected, deal = expected_cents(row["live_price"], row["live_savings"], int(row["qty"]))
                terms += 1
                lines.append(
                    f"| {name} | {row['qty']} | {row['live_price']} | {row['live_savings'].replace('|', '\\|')} | {deal} | "
                    f"{(expected or 0) / 100:.2f} | | terms checked, no cart |"
                )
                continue
            if not row["cart_subtotal"]:
                lines.append(f"| {name} | {row['qty']} | | | | | | not checked: {row['note']} |")
                continue
            expected, deal = expected_cents(row["live_price"], row["live_savings"], int(row["qty"]))
            cart = to_cents(row["cart_subtotal"])
            former = percentage_rule_cents(row["live_price"], row["live_savings"], int(row["qty"]))
            note = f" ({row['note']})" if row["note"] else ""
            if former is not None:
                # Not applied any more; recorded as the evidence for excluding them.
                percentage += 1
                percentage_agree += former == cart
                result = (
                    "percentage rule matched" if former == cart else f"**percentage rule off by {cart - former}¢**"
                ) + f": it gave {former / 100:.2f}{note}"
                deal = "not applied (percentage)"
                expected = None
            else:
                checked += 1
                agree += expected == cart
                result = ("match" if expected == cart else f"**differs by {(cart or 0) - (expected or 0)}¢**") + note
            lines.append(
                f"| {name} | {row['qty']} | {row['live_price']} | {row['live_savings'].replace('|', '\\|')} | {deal} | "
                f"{'–' if expected is None else f'{expected / 100:.2f}'} | {(cart or 0) / 100:.2f} | {result} |"
            )
        totals[retailer] = (agree, checked, terms)
        summary = f"{agree} of {checked} carts match our rules." if checked else ""
        if percentage:
            summary += (
                f" {percentage} percentage deals: the former percentage rule matched {percentage_agree},"
                " so percentage deals are no longer applied (see the finding above)."
            )
        if terms:
            summary += f" {terms} deals checked against their live product-page terms only: the cart needs a login."
        lines += ["", summary.strip(), ""]
    (SNAPSHOT / "checkout-evidence.md").write_text("\n".join(lines), encoding="utf-8")
    for retailer, (agree, checked, terms) in totals.items():
        print(f"{retailer}: {agree}/{checked} carts match, {terms} terms only")


if __name__ == "__main__":
    main()
