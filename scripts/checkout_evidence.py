"""Compare live cart subtotals with our pricing rules (PR-03 checkout evidence).

Reads data/snapshot/checkout-<retailer>.csv (written by scripts/scrape/checkout.ts)
and writes data/snapshot/checkout-evidence.md. For each sampled deal, our rule
is applied to the *live* unit price and deal wording, so a price change since
the snapshot does not count as a disagreement; the cart subtotal must equal it.

Run from the repository root: python3 scripts/checkout_evidence.py
"""

import csv
from pathlib import Path

from derive_offer_prices import derive_offer, to_cents

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "data" / "snapshot"
RETAILERS = ["fairprice", "cold-storage", "redmart"]


def expected_cents(price: str, savings: str, qty: int) -> tuple[int | None, str]:
    """Our line total for `qty` packs, and the deal it used, from live price and wording."""
    offer = derive_offer({"Product Price": price, "Original Price": "", "Savings": savings})
    if not offer["eligible"]:
        return None, ""
    unit, deal = offer["unit_price_cents"], offer["multibuy"]
    if deal is None:
        return unit * qty, "no deal applied"
    deals = qty // deal["packsPerDeal"]
    rest = qty - deals * deal["packsPerDeal"]
    return deals * deal["dealPriceCents"] + rest * unit, f"{deal['packsPerDeal']} for {deal['dealPriceCents'] / 100:.2f}"


def main() -> None:
    lines = [
        "# Checkout evidence for multibuys (PR-03)",
        "",
        "Generated by `scripts/checkout_evidence.py` from live carts filled by `scripts/scrape/checkout.ts`.",
        "Each sampled deal was put in a cart at one pack more than the deal needs, so the remaining pack",
        "is tested too. *Expected* applies our curation and pricing rules to the live unit price and deal",
        "wording; *Cart* is the retailer's own subtotal. Nothing was ordered.",
        "",
    ]
    totals = {}
    for retailer in RETAILERS:
        path = SNAPSHOT / f"checkout-{retailer}.csv"
        if not path.exists():
            lines += [f"## {retailer}", "", "Not checked yet.", ""]
            continue
        rows = list(csv.DictReader(open(path, encoding="utf-8")))
        lines += [
            f"## {retailer}",
            "",
            "| Product | Qty | Unit | Deal wording | Our deal | Expected | Cart | Result |",
            "| --- | ---: | ---: | --- | --- | ---: | ---: | --- |",
        ]
        agree = checked = terms = 0
        for row in rows:
            name = row["url"].rstrip("/").rsplit("/", 1)[-1].removesuffix(".html")
            if row["note"] == "terms only":
                expected, deal = expected_cents(row["live_price"], row["live_savings"], int(row["qty"]))
                terms += 1
                lines.append(
                    f"| {name} | {row['qty']} | {row['live_price']} | {row['live_savings'].replace('|', '\\|')} | {deal} | "
                    f"{(expected or 0) / 100:.2f} | | terms checked, no cart |"
                )
                continue
            if row["note"] or not row["cart_subtotal"]:
                lines.append(f"| {name} | {row['qty']} | | | | | | not checked: {row['note']} |")
                continue
            expected, deal = expected_cents(row["live_price"], row["live_savings"], int(row["qty"]))
            cart = to_cents(row["cart_subtotal"])
            checked += 1
            agree += expected == cart
            result = "match" if expected == cart else f"**differs by {(cart or 0) - (expected or 0)}¢**"
            lines.append(
                f"| {name} | {row['qty']} | {row['live_price']} | {row['live_savings'].replace('|', '\\|')} | {deal} | "
                f"{(expected or 0) / 100:.2f} | {(cart or 0) / 100:.2f} | {result} |"
            )
        totals[retailer] = (agree, checked, terms)
        summary = f"{agree} of {checked} carts match." if checked else ""
        if terms:
            summary += f" {terms} deals checked against their live product-page terms only: the cart needs a login."
        lines += ["", summary.strip(), ""]
    (SNAPSHOT / "checkout-evidence.md").write_text("\n".join(lines), encoding="utf-8")
    for retailer, (agree, checked, terms) in totals.items():
        print(f"{retailer}: {agree}/{checked} carts match, {terms} terms only")


if __name__ == "__main__":
    main()
